// a position with no track falls back to the hands-on engineering set, which is what the app
// shipped with before the management positions were added
const DEFAULT_TRACK = { core: 'engineering', specialties: ['se-craft'] }

function getTrack(role) {
  return ROLE_TRACKS[role] || DEFAULT_TRACK
}

// true for the leadership and management positions, so a page can change its wording
export function isManagementRole(role) {
  return getTrack(role).core === 'management'
}

// which level wording to show: a manager ladder reads differently to an engineer ladder
export function getLevelHints(role) {
  return isManagementRole(role) ? MANAGEMENT_LEVEL_HINTS : ENGINEERING_LEVEL_HINTS
}

// core subjects first, then whatever is specific to the chosen position
export function getCategoriesForRole(role) {
  const track = getTrack(role)
  const core = track.core === 'management' ? MANAGEMENT_CORE_CATEGORIES : CORE_CATEGORIES
  const specialties = track.specialties.map((id) => SPECIALTY_BY_ID[id]).filter(Boolean)
  return [...core, ...specialties]
}

// flattens the categories down to a plain topic list - handy for counting progress
export function getTopicsForRole(role) {
  return getCategoriesForRole(role).flatMap((category) => category.topics)
}
